/**
 * Ритм голосового супроводу вправи (мобільний застосунок проговорює фази руху й рахує повтори).
 * Фрази кожного ритму — у перекладах застосунку; тут лише тип.
 */
export enum VoicePattern {
  /** «Вниз — вверх», рахунок повторів (присідання) */
  SQUAT = 'squat',
  /** «Шаг и вниз — вверх» (випади) */
  LUNGE = 'lunge',
  /** «Опускаемся — поднимаемся» (віджимання) */
  PUSH = 'push',
  /** «Таз вверх — опускаем» (місток) */
  BRIDGE = 'bridge',
  /** «Поднимаем — опускаем» (підйоми на носки, «супермен») */
  RAISE = 'raise',
  /** «Тянемся — возвращаемся» (птах-собака) */
  REACH = 'reach',
  /** «Влево — вправо» (повороти, нахили в сторони) */
  TWIST = 'twist',
  /** «Наклон — выпрямляемся» */
  FOLD = 'fold',
  /** Рахунок у темпі (марш, біг на місці) */
  MARCH = 'march',
  /** Рахунок у темпі («зірочка») */
  JACKS = 'jacks',
  /** Рахунок і «меняем направление» посередині (кола руками/тазом) */
  CIRCLE = 'circle',
  /** Утримання: «держим», залишок часу (планка, баланс) */
  HOLD = 'hold',
  /** «Вдох — выдох» */
  BREATH = 'breath',
  /** Крокомір: скільки кроків залишилось */
  STEPS = 'steps',
}

export const ALL_VOICE_PATTERNS: VoicePattern[] = Object.values(VoicePattern);
